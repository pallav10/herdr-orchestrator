#!/usr/bin/env node
// Renders an Archify spec (validated by `archify deliver`) and writes src/diagrams/<id>.js for index.html.
// Usage: node tools/sync-diagram.mjs <spec.json> <id> "<tab label>"   (ARCHIFY_BIN overrides the CLI path)
// Tab order is the order of the diagram <script> tags in index.html.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [specArg, id, tab] = process.argv.slice(2);
if (!specArg || !/^[a-z][a-z0-9-]*$/.test(id ?? '') || !tab) {
  console.error('usage: node tools/sync-diagram.mjs <spec.json> <id> "<tab label>"');
  process.exit(2);
}

const visualDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const specPath = path.resolve(specArg);
const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const archify = process.env.ARCHIFY_BIN ?? path.join(homedir(), '.agents/skills/archify/bin/archify.mjs');
const workDir = mkdtempSync(path.join(tmpdir(), 'herdr-visual-'));

try {
  const htmlPath = path.join(workDir, 'diagram.html');
  execFileSync(process.execPath, [archify, 'deliver', spec.diagram_type, specPath, htmlPath, '--quality', 'showcase', '--json'], { stdio: ['ignore', 'ignore', 'inherit'] });
  const html = readFileSync(htmlPath, 'utf8');
  const start = html.indexOf('<svg ');
  const end = html.indexOf('</svg>', start);
  if (start < 0 || end < 0) throw new Error('rendered page has no <svg> block');
  const diagram = {
    id,
    tab,
    type: spec.diagram_type,
    title: spec.meta.title,
    subtitle: spec.meta.subtitle ?? '',
    views: spec.meta.views ?? [],
    cards: spec.cards ?? [],
    svg: html.slice(start, end + '</svg>'.length)
  };
  const out = path.join(visualDir, 'src/diagrams', `${id}.js`);
  const source = path.relative(visualDir, specPath);
  writeFileSync(out, `// Generated by tools/sync-diagram.mjs from ${source}. Edit the spec and re-run; do not edit by hand.\nHerdrVisual.diagrams.push(${JSON.stringify(diagram, null, 2)});\n`);
  console.log(path.relative(visualDir, out));
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
